/**
 * Copies Home Assistant's default theme (every CSS variable on <html>, light and dark) and the
 * Roboto fonts from the running dev instance, so cards rendered outside HA (docs, tests) look
 * the same as on a dashboard. Run after `pnpm hass:up`, again when HA changes its theme:
 *
 *   pnpm hass:sync-theme
 */
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import globalSetup, { STORAGE_STATE } from "../src/global-setup.ts";
import { getJson, HASS_URL, isObject, readToken } from "../src/hass.ts";

const THEME_FILE = fileURLToPath(
  new URL("../../packages/shared/src/preview/ha-theme.ts", import.meta.url)
);
const FONT_DIR = fileURLToPath(new URL("../../apps/web/public/fonts/roboto/", import.meta.url));
// The weights the cards use: 400, 500 and 600 (drawn with Bold, as in HA).
const FONTS = ["Roboto-Regular", "Roboto-Medium", "Roboto-Bold"];

type Vars = Record<string, string>;

await globalSetup();
const config = await getJson("/api/config", await readToken());
const version = isObject(config) && typeof config.version === "string" ? config.version : "unknown";
const browser = await chromium.launch();

const themeVars = async (colorScheme: "light" | "dark"): Promise<Vars> => {
  const context = await browser.newContext({ storageState: STORAGE_STATE, colorScheme });
  const page = await context.newPage();
  await page.goto(`${HASS_URL}/power-flow`);
  await page.locator("hui-view").first().waitFor({ state: "attached" });
  const vars = await page.evaluate(() => {
    const style = getComputedStyle(document.documentElement);
    return Object.fromEntries(
      [...style]
        .filter((name) => name.startsWith("--"))
        .map((name) => [name, style.getPropertyValue(name).trim()])
    );
  });
  await context.close();
  return vars;
};

const light = await themeVars("light");
const dark = await themeVars("dark");
await browser.close();

const block = (vars: Vars) =>
  Object.entries(vars)
    .toSorted(([a], [b]) => a.localeCompare(b))
    .map(([name, value]) => `  ${name}: ${value.replaceAll("`", "\\`")};`)
    .join("\n");

const darkOnly = Object.fromEntries(
  Object.entries(dark).filter(([name, value]) => light[name] !== value)
);

await writeFile(
  THEME_FILE,
  `// Generated by e2e/scripts/sync-ha-theme.ts from Home Assistant ${version}; do not edit.

/** Every CSS variable Home Assistant's default theme sets on <html>, light mode. */
export const haThemeLight = \`
${block(light)}
\`;

/** The variables that differ in dark mode; apply on top of the light ones. */
export const haThemeDark = \`
${block(darkOnly)}
\`;
`
);

await mkdir(FONT_DIR, { recursive: true });
await Promise.all(
  FONTS.map(async (font) => {
    const response = await fetch(`${HASS_URL}/static/fonts/roboto/${font}.woff2`);
    if (!response.ok) {
      throw new Error(`${font}: ${response.status}`);
    }
    await writeFile(`${FONT_DIR}${font}.woff2`, new Uint8Array(await response.arrayBuffer()));
  })
);

console.warn(
  `Theme of Home Assistant ${version}: ${Object.keys(light).length} variables, ${Object.keys(darkOnly).length} differ in dark mode.`
);
